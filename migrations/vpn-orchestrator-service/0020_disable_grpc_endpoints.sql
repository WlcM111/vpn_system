-- vpn-orchestrator: gRPC-конфигурации больше не выдаются ни на одном сервере.
--
-- Выключение — данными, а не удалением кода. Каждая строка vpn_grpc_endpoints
-- получает enabled = FALSE, и для её сервера gRPC пропадает разом из двух мест:
-- из подписки (ссылка type=grpc) и из желаемого состояния узла (учётка в
-- gRPC-инбаунде). Таблица, Admin API, сборщик ссылки и регистрация учёток на
-- узлах остаются рабочими — возможность сохранена целиком.
--
-- Env-фолбэк (GRPC_ADDRESS) выключенные строки не перекрывает: он действует
-- только для пустой таблицы (см. grpcEndpointsForIssue в grpc_service.go).
--
-- Уже заведённые учётки в gRPC-инбаундах узлов эта миграция не трогает. Они
-- снимаются штатно при отзыве доступа: отзыв без Scope тотальный, агент снимает
-- все известные ему профили пользователя, включая gRPC.
--
-- Вернуть gRPC на сервере:
--   UPDATE vpn_grpc_endpoints SET enabled = TRUE, updated_at = now()
--   WHERE grpc_key = '<ключ>';
-- При GRPC_CONFIG_ENABLED=true ссылка появится в подписке сразу, а учётки на
-- узле заведёт ближайший проход reconcile.
--
-- Контейнер migrate применяет файл один раз (учёт в schema_migrations), поэтому
-- строки, включённые после него вручную, следующие выкатки не выключают.

UPDATE vpn_grpc_endpoints
SET enabled = FALSE,
    updated_at = now()
WHERE enabled = TRUE;
