-- vpn-orchestrator: лимит пользователей на ноду — 400.
--
-- max_users — мягкий лимит балансировщика (ServerLoad.HasCapacity): пока у
-- ноды выданных учёток меньше лимита, она получает новых пользователей. Когда
-- лимит исчерпан на всех живых нодах страны, при BALANCER_SOFT_OVERFLOW=true
-- выдаётся наименее загруженная (с предупреждением в журнале), при false
-- страна пропадает из подписки. На дашборде это знаменатель процента
-- «Загрузка нод (% заполнения)».
--
-- Ноды, заведённые через Admin API без max_users, получали 200. Этого мало:
-- у каждого пользователя по профилю на страну, и при недоступных нодах все
-- пользователи страны приходятся на оставшиеся. Миграция поднимает лимит:
--   * 1..399      → 400;
--   * 400 и выше  → без изменений (лимит не уменьшается);
--   * 0 и меньше  → без изменений («без лимита», см. HasCapacity).
-- Значение по умолчанию столбца — тоже 400; Admin API с этим изменением
-- ставит 400, если max_users не передан (DefaultNodeMaxUsers).
--
-- Доступ пользователей не меняется: лимит влияет только на выбор ноды для
-- новых выдач. Прежний код с новым значением работает (читает его из базы).
--
-- Контейнер migrate применяет файл один раз (учёт в schema_migrations):
-- лимит, изменённый после этого вручную, следующие выкатки не перезаписывают.
-- Лимит отдельной ноды:
--   UPDATE vpn_servers SET max_users = <число>, updated_at = now()
--   WHERE server_key = '<ключ>';

ALTER TABLE vpn_servers ALTER COLUMN max_users SET DEFAULT 400;

UPDATE vpn_servers
SET max_users = 400,
    updated_at = now()
WHERE max_users BETWEEN 1 AND 399;
