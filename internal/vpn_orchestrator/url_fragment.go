package vpn_orchestrator

import (
	"net/url"
	"strings"
)

// ============================================================================
// Кодирование названия профиля для фрагмента ссылки (часть после #).
//
// url.QueryEscape предназначен для query-строки, где пробел по стандарту
// application/x-www-form-urlencoded кодируется как "+". В URL-фрагменте "+"
// означает буквальный плюс, поэтому клиенты показывают "Литва+-+Маленький+Пинг".
//
// Для фрагмента пробел должен быть %20 — это кодирование однозначно
// декодируется всеми клиентами.
// ============================================================================

// escapeFragment кодирует строку для использования после "#" в ссылке.
func escapeFragment(s string) string {
	return strings.ReplaceAll(url.QueryEscape(s), "+", "%20")
}
